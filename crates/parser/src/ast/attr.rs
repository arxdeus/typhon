impl Attr {
    /// the reference implementation `attrName`: names shown by `toPythonString`; empty for hidden keys.
    pub fn py_name(self) -> &'static str {
        use Attr::*;
        match self {
            ExprSequenceItem | ExprStarSequenceItem | ExprList | ExprSet | ExprDict
            | ExprPartial | ExprStarArgument | ExprKwStarArgument | ExprOrderedCall | ExprTime
            | ExprVirtual | MaybeLiteral => "",
            a => a.name(),
        }
    }
    /// the reference implementation `attributeName`: names shown by `debug dump`.
    pub fn display_name(self) -> Option<&'static str> {
        match self {
            Attr::ExprVirtual | Attr::MaybeLiteral => None,
            a => Some(a.name()),
        }
    }
}

/// `BindingsAttribute::CaptureType`.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum CaptureType {
    Read,
    Global,
    Nonlocal,
}

/// `BindingsAttribute::Binding`.
#[derive(Clone, Debug, PartialEq, Eq, Default, Serialize, Deserialize)]
pub struct Binding {
    pub name: String,
    pub count: usize,
    pub is_nonlocal: bool,
}

/// every printer sorts the keys).
#[derive(Clone, Debug, PartialEq, Eq, Default, Serialize, Deserialize)]
pub struct BindingsAttr {
    pub captures: BTreeMap<String, CaptureType>,
    pub bindings: BTreeMap<String, Binding>,
    pub local_renames: BTreeMap<String, String>,
}

/// Attribute payload (`ir::Attribute` subclass).
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub enum AttrValue {
    /// Plain `ir::Attribute` (flag).
    Flag,
    /// `ir::IntValueAttribute`.
    Int(i64),
    /// `ir::StringValueAttribute`.
    Str(String),
    /// `ir::StringListAttribute`.
    StrList(Vec<String>),
    /// `ir::KeyValueAttribute`.
    KeyValue(BTreeMap<String, String>),
    /// `BindingsAttribute`.
    Bindings(BindingsAttr),
}

impl AttrValue {
    /// the reference implementation `operator<<(ostream, Attribute)` (`doFormat`).
    pub fn display(&self) -> String {
        match self {
            AttrValue::Flag => String::new(),
            AttrValue::Int(i) => i.to_string(),
            AttrValue::Str(s) => s.clone(),
            AttrValue::StrList(v) => v.join(","),
            AttrValue::KeyValue(m) => m.values().cloned().collect::<Vec<_>>().join(","),
            AttrValue::Bindings(_) => "Bindings".into(),
        }
    }
}

/// Insertion-ordered attribute map (`ir::AttributeMap`, a small vector of pairs).
#[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]
pub struct Attrs {
    values: Vec<(Attr, AttrValue)>,
}

impl Attrs {
    pub fn new() -> Self {
        Self::default()
    }
    pub fn is_empty(&self) -> bool {
        self.values.is_empty()
    }
    pub fn len(&self) -> usize {
        self.values.len()
    }
    /// `setAttribute(key, value)`: replaces in place if present, else appends.
    pub fn set_value(&mut self, key: Attr, value: AttrValue) {
        if let Some(slot) = self.values.iter_mut().find(|(k, _)| *k == key) {
            slot.1 = value;
        } else {
            self.values.push((key, value));
        }
    }
    /// `setAttribute(key)`.
    pub fn set(&mut self, key: Attr) {
        self.set_value(key, AttrValue::Flag)
    }
    /// `setAttribute(key, int64_t)`.
    pub fn set_int(&mut self, key: Attr, v: i64) {
        self.set_value(key, AttrValue::Int(v))
    }
    /// `setAttribute(key, std::string)`.
    pub fn set_str(&mut self, key: Attr, v: impl Into<String>) {
        self.set_value(key, AttrValue::Str(v.into()))
    }
    pub fn has(&self, key: Attr) -> bool {
        self.values.iter().any(|(k, _)| *k == key)
    }
    pub fn get(&self, key: Attr) -> Option<&AttrValue> {
        self.values.iter().find(|(k, _)| *k == key).map(|(_, v)| v)
    }
    pub fn get_mut(&mut self, key: Attr) -> Option<&mut AttrValue> {
        self.values.iter_mut().find(|(k, _)| *k == key).map(|(_, v)| v)
    }
    pub fn get_int(&self, key: Attr) -> Option<i64> {
        match self.get(key) {
            Some(AttrValue::Int(i)) => Some(*i),
            _ => None,
        }
    }
    pub fn get_str(&self, key: Attr) -> Option<&str> {
        match self.get(key) {
            Some(AttrValue::Str(s)) => Some(s),
            _ => None,
        }
    }
    pub fn get_str_list(&self, key: Attr) -> Option<&Vec<String>> {
        match self.get(key) {
            Some(AttrValue::StrList(s)) => Some(s),
            _ => None,
        }
    }
    pub fn get_str_list_mut(&mut self, key: Attr) -> Option<&mut Vec<String>> {
        match self.get_mut(key) {
            Some(AttrValue::StrList(s)) => Some(s),
            _ => None,
        }
    }
    pub fn get_key_value(&self, key: Attr) -> Option<&BTreeMap<String, String>> {
        match self.get(key) {
            Some(AttrValue::KeyValue(s)) => Some(s),
            _ => None,
        }
    }
    pub fn get_bindings(&self) -> Option<&BindingsAttr> {
        match self.get(Attr::Bindings) {
            Some(AttrValue::Bindings(s)) => Some(s),
            _ => None,
        }
    }
    pub fn get_bindings_mut(&mut self) -> Option<&mut BindingsAttr> {
        match self.get_mut(Attr::Bindings) {
            Some(AttrValue::Bindings(s)) => Some(s),
            _ => None,
        }
    }
    /// `eraseAttribute(key)`.
    pub fn erase(&mut self, key: Attr) {
        self.values.retain(|(k, _)| *k != key);
    }
    pub fn iter(&self) -> impl Iterator<Item = (Attr, &AttrValue)> {
        self.values.iter().map(|(k, v)| (*k, v))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn attr_values() {
        assert_eq!(Attr::Module as i32, 201);
        assert_eq!(Attr::NoExtend as i32, 235);
        assert_eq!(Attr::MaybeLiteral as i32, 201 + Attr::ALL.len() as i32 - 1);
        assert_eq!(Attr::from_i32(203), Some(Attr::Bindings));
        let mut a = Attrs::new();
        a.set(Attr::Tuple);
        a.set_str(Attr::Module, "m");
        a.set_str(Attr::Module, "n");
        assert_eq!(a.len(), 2);
        assert_eq!(a.get_str(Attr::Module), Some("n"));
        a.erase(Attr::Tuple);
        assert!(!a.has(Attr::Tuple));
    }
}
