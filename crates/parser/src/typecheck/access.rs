impl<'a> TypecheckVisitor<'a> {
    /// `visit(IdExpr*)`: resolve an identifier, check captures, set type.
    pub fn visit_id(&mut self, e: ExprId) -> Result<()> {
        let types = self.types();
        let value = self.ast()[e].kind.as_id().unwrap().value.clone();
        let t = self.get_time();
        let Some(mut val) = self.find(&value, t) else {
            let src = self.ast()[e].src;
            typhon_common::bail_e!(ErrorKind::ID_NOT_FOUND, src, value);
        };

        // If this is an overload, use the dispatch function
        let vname = val.borrow().canonical_name.clone();
        if self.is_unbound_expr(e) && self.has_overloads(&vname) {
            let d = self.get_dispatch(&vname)?.expect("no dispatch");
            val = self.force_find(&types.func_name(d));
        }

        // If we are accessing an outside variable, capture it or raise an error
        self.check_capture(&val)?;

        // Replace the variable with its canonical name
        let (vname, vty, is_var) = {
            let v = val.borrow();
            (v.canonical_name.clone(), v.ty(), v.is_var(&types))
        };
        self.set_id_value(e, &vname);

        // Set up type
        let mut value_type = self.instantiate_type(vty, None)?;
        // the builtin type object has no argument.
        // type[T] remains the representation of a class value.
        if vname == stdlib().type_ {
            let metaclass = self.get_metaclass_type()?;
            value_type = self.instantiate_type_var(metaclass)?;
        }
        let et = self.ety(e);
        self.unify(et, value_type)?;
        if let Some(f) = types.get_func(et) {
            self.set_id_value(e, &types.func_name(f)); // resolve overloads
        }
        if types.is(et, &stdlib().capsule) && !self.ast()[e].attrs.has(Attr::AutoGenerated) {
            self.ast_mut()[e].attrs.set(Attr::AutoGenerated);
            let f = self.id_n(&mangle::mangled_method("", "Capsule", "_get", 0, 0));
            let c = self.call_n(f, vec![e]);
            self.result_expr = self.transform(Some(c))?;
            return Ok(());
        }

        // Realize a type or a function if possible and replace the identifier with
        // a qualified identifier or a static expression (e.g., `foo` -> `foo[int]`)
        if types.can_realize(et) {
            if types.get_static(et).is_some() {
                let s = types.static_expr(et, &mut self.cache.ast);
                self.result_expr = self.transform(s)?;
                return Ok(());
            }
            if !is_var {
                if !(self.ast()[e].attrs.has(Attr::ExprDoNotRealize) && types.get_func(et).is_some()) {
                    if let Some(r) = self.realize(et)? {
                        self.set_id_value(e, &types.realized_name(r));
                        self.set_done_expr(e);
                    }
                }
            } else {
                self.realize(et)?;
                self.set_done_expr(e);
            }
        }

        // If this identifier needs __used__ checks (see @c ScopeVisitor), add them
        if !self.ast()[e].attrs.has(Attr::ExprNoUndefCheck) {
            let control_var = format!("{vname}{VAR_USED_SUFFIX}");
            if self.find(&control_var, self.get_time()).is_some() {
                let i = self.id_n("__internal__");
                let d = self.dot_n(i, "undef");
                let cv = self.id_n(&control_var);
                let un = self.get_unmangled_name(&vname);
                let s = self.n_expr(StringExpr::new(un, ""));
                let c = self.call_n(d, vec![cv, s]);
                let check = self.n_stmt(ExprStmt { expr: Some(c) });
                self.ast_mut()[e].attrs.set(Attr::ExprNoUndefCheck);
                let se = self.n_expr(StmtExpr { items: vec![check], expr: Some(e) });
                self.result_expr = self.transform(Some(se))?;
            }
        }
        Ok(())
    }

    fn set_id_value(&mut self, e: ExprId, v: &str) {
        if let Some(i) = self.ast_mut()[e].kind.as_id_mut() {
            i.value = v.to_string();
        }
    }

    /// `checkCapture(item)`: access identifiers outside of the current function/class
    /// scope. Either use them as-is (globals), capture them if allowed (nonlocals), or
    /// raise an error.
    pub fn check_capture(&mut self, val: &ItemRef) -> Result<()> {
        let types = self.types();
        if !self.ctx.borrow().is_outer(val) {
            return Ok(());
        }
        let (is_type, is_generic, is_func, is_var, is_global, vbase, vmodule, vname) = {
            let v = val.borrow();
            (
                v.is_type(&types),
                v.is_generic(),
                v.is_func(&types),
                v.is_var(&types),
                v.is_global(),
                v.base_name().to_string(),
                v.module().to_string(),
                v.canonical_name.clone(),
            )
        };
        if (is_type && !is_generic) || is_func {
            return Ok(());
        }

        // Ensure that outer variables can be captured (i.e., do not cross no-capture
        // boundary).
        let (local_generic, parent_class_generic, cross, func) = {
            let c = self.ctx.borrow();
            let local_generic = is_generic && vbase == c.base_name().as_str();
            let n = c.bases.len();
            let parent_class_generic = is_generic
                && !c.base_ref().is_type()
                && (n > 1 && c.bases[n - 2].is_type() && c.bases[n - 2].name.as_str() == vbase);
            let mut cross = false;
            let mut i = n;
            while i > 0 {
                i -= 1;
                if c.bases[i].name.as_str() == vbase {
                    break;
                }
                if !local_generic && !parent_class_generic {
                    cross = true;
                }
            }
            (local_generic, parent_class_generic, cross, c.base_ref().func)
        };

        // Mark methods (class functions that access class generics)
        if parent_class_generic {
            if let Some(f) = func {
                self.ast_mut()[f].attrs.set(Attr::Method);
            }
        }
        // Ignore generics
        if parent_class_generic || local_generic {
            return Ok(());
        }
        // Case: a global variable that has not been marked with `global` statement
        if is_var && is_global {
            self.register_global(&vname);
            return Ok(());
        }
        // Not in module; probably some capture
        if vmodule != self.ctx.borrow().module().as_str() {
            return Ok(());
        }
        // Check if a real variable (not a static) is defined outside the current scope
        let src = self.src;
        if cross {
            typhon_common::bail_e!(ErrorKind::ID_CANNOT_CAPTURE, src, self.get_user_facing_name(&vname));
        }
        // Case: a nonlocal variable that has not been marked with `nonlocal` statement
        //       and capturing is *not* enabled
        typhon_common::bail_e!(ErrorKind::ID_NONLOCAL, src, self.get_user_facing_name(&vname));
    }

    /// `visit(DotExpr*)`: transform a dot expression. Select the best method overload if
    /// possible.
    /// `obj.__class__` -> `type(obj)`, `cls.__name__` -> `"class"`,
    /// `obj.method` -> `cls.method(obj, ...)` (or `cls.method(obj)` for `@property`),
    /// `obj.member` -> see [`Self::get_class_member`].
    pub fn visit_dot(&mut self, e: ExprId) -> Result<()> {
        // Check if this is being called from CallExpr (e.g., foo.bar(...))
        // and mark it as such (to inline useless partial expression)
        // PORT-NOTE: the node stack keeps only source locations; the parent call is
        // registered by `visit_call` (see `call::parent_call_of`).
        let parent_call = super::call::parent_call_of(e).filter(|c| self.ast()[*c].attrs.has(Attr::ParentCallExpr));

        // Flatten imports:
        //   `a.b.c`      -> canonical name of `c` in `a.b` if `a.b` is an import
        //   `a.B.c`      -> canonical name of `c` in class `a.B`
        //   `python.foo` -> internal.python._get_identifier("foo")
        let mut chain: Vec<String> = vec![];
        let mut head = e;
        while let Some(d) = self.ast()[head].kind.as_dot() {
            chain.push(d.member.clone());
            head = d.expr.expect("dot without expr");
        }
        let mut fin = e;
        if let Some(id) = self.ast()[head].kind.as_id() {
            // Case: a.bar.baz
            chain.push(id.value.clone());
            chain.reverse();
            let (mut pos, val) = self.get_import_chain(&chain)?;
            let cur_module = self.ctx.borrow().module().to_string();
            match val {
                None => {
                    // Python capture
                    let caps = self.ctx.borrow().base_ref().py_captures.clone();
                    typhon_common::seqassert!(caps.is_some(), "unexpected py capture");
                    caps.unwrap().borrow_mut().insert(chain[0].clone());
                    let p = self.id_n("__pyenv__");
                    let s = self.n_expr(StringExpr::new(chain[0].clone(), ""));
                    fin = self.n_expr(IndexExpr { expr: Some(p), index: Some(s) });
                }
                Some(val) => {
                    let (vmod, vcanon) = {
                        let v = val.borrow();
                        (v.module().to_string(), v.canonical_name.clone())
                    };
                    if vmod == "std.python" && cur_module != vmod {
                        // Import from python (e.g., pyobj.foo)
                        let i = self.id_n("internal");
                        let p = self.dot_n(i, "python");
                        let g = self.dot_n(p, "_get_identifier");
                        let s = self.n_expr(StringExpr::new(chain[pos].clone(), ""));
                        pos += 1;
                        let c = self.call_n(g, vec![s]);
                        fin = self.tr(c)?;
                    } else if vmod == cur_module && pos == 1 {
                        let i = self.id_n(&chain[0]);
                        fin = self.transform_allow(Some(i), true)?.unwrap();
                    } else {
                        fin = self.id_n(&vcanon);
                    }
                }
            }
            while pos < chain.len() {
                fin = self.dot_n(fin, &chain[pos]);
                pos += 1;
            }
        }
        if let Some(dot) = self.ast()[fin].kind.as_dot().cloned() {
            let d = self.ast_mut()[e].kind.as_dot_mut().unwrap();
            d.expr = dot.expr;
            d.member = dot.member;
        } else {
            if self.ast()[e].attrs.has(Attr::ExprDoNotRealize) {
                self.ast_mut()[fin].attrs.set(Attr::ExprDoNotRealize);
            }
            self.result_expr = self.transform(Some(fin))?;
            return Ok(());
        }

        let (inner, member) = {
            let d = self.ast()[e].kind.as_dot().unwrap();
            (d.expr.unwrap(), d.member.clone())
        };
        // Special case: obj.__class__
        if member == "__class__" {
            let f = self.id_n(&mangle::mangled_method("", &stdlib().type_, "__new__", 0, 0));
            let c = self.call_n(f, vec![inner]);
            self.result_expr = self.transform(Some(c))?;
            return Ok(());
        }
        let inner = self.tr(inner)?;
        self.ast_mut()[e].kind.as_dot_mut().unwrap().expr = Some(inner);
        let et = self.expr_type(e);
        let (new_expr, found) = self.get_attr(inner, &member, et, parent_call)?;
        if !found {
            let src = self.ast()[e].src;
            let t = self.extract_type_expr(inner);
            typhon_common::bail_e!(ErrorKind::DOT_NO_ATTR, src, self.types().pretty_string(t), member);
        }
        if new_expr.is_some() {
            self.result_expr = new_expr;
        } else if self.ast()[inner].done && self.realize(self.ety(e))?.is_some() {
            self.set_done_expr(e);
        }
        Ok(())
    }

    fn wrap_side(&mut self, has_side: bool, expr: ExprId, mut e: ExprId, parent_call: bool) -> Result<Option<ExprId>> {
        if has_side {
            let s = self.n_stmt(ExprStmt { expr: Some(expr) });
            e = self.n_expr(StmtExpr { items: vec![s], expr: Some(e) });
        }
        if parent_call {
            self.ast_mut()[e].attrs.set(Attr::ExprDoNotRealize);
        }
        self.transform(Some(e))
    }

    /// `getAttr(expr, member, type, parentCall)`: `(replacement, handled)`.
    pub fn get_attr(&mut self, expr: ExprId, member: &str, ty: Option<TypeId>, call: Option<ExprId>) -> Result<(Option<ExprId>, bool)> {
        let types = self.types();
        let et = self.ety(expr);
        if types.is(et, &stdlib().optional) && types.has_unbounds(et, false) {
            return Ok((None, true));
        }
        let has_side = self.has_side_effect(expr);
        let pc = call.is_some();
        let is_type = Self::is_type_expr(self.cache, expr);

        // Special case: fn.__name__
        // Should go before cls.__name__ to allow printing generic functions
        // NOTE: NO SIDE EFFECTS! (because of generic function support!)
        if types.get_func(self.extract_type_expr(expr)).is_some() && member == "__name__" {
            let s = types.pretty_string(self.extract_type_expr(expr));
            return Ok((Some(self.n_expr(StringExpr::new(s, ""))), true));
        }
        if let Some(p) = types.get_partial(et) {
            if member == "__name__" {
                let s = self.n_expr(StringExpr::new(types.pretty_string(p), ""));
                return Ok((self.wrap_side(has_side, expr, s, pc)?, true));
            }
        }
        // Special case: fn.__llvm_name__ or obj.__llvm_name__
        if member == "__llvm_name__" {
            if self.realize(et)?.is_some() {
                let s = self.n_expr(StringExpr::new(types.realized_name(et), ""));
                return Ok((self.wrap_side(has_side, expr, s, pc)?, true));
            }
            return Ok((None, true));
        }
        if is_type && member == "__generic_name__" {
            let t = self.extract_type(et);
            // No side effects here, otherwise will not typecheck
            if let Some(c) = types.get_class(t) {
                let n = types.class_name(c).unwrap().to_string();
                return Ok((Some(self.n_expr(StringExpr::new(n, ""))), true));
            }
            return Ok((None, true));
        }
        // Special case: cls.__name__
        if is_type && member == "__name__" {
            if self.realize(et)?.is_some() {
                let s = types.pretty_string(self.extract_type_expr(expr));
                let s = self.n_expr(StringExpr::new(s, ""));
                return Ok((self.wrap_side(has_side, expr, s, pc)?, true));
            }
            return Ok((None, true));
        }
        // Special case: cls.__mro__
        if is_type && member == "__mro__" {
            if self.realize(et)?.is_some() {
                let t = types.get_class(self.extract_type_expr(expr)).unwrap();
                let bases = self.get_mro(t)?;
                let items: Vec<ExprId> = bases.iter().map(|b| self.id_n(&types.realized_name(*b))).collect();
                let tu = self.n_expr(TupleExpr { items });
                return Ok((self.wrap_side(has_side, expr, tu, pc)?, true));
            }
            return Ok((None, true));
        }
        // Special case: expr.__is_static__
        if member == "__is_static__" {
            if self.ast()[expr].done {
                let b = self.n_expr(BoolExpr { value: types.get_static(et).is_some() });
                return Ok((self.wrap_side(has_side, expr, b, pc)?, true));
            }
            return Ok((None, true));
        }
        // Special case: cls.__id__
        if is_type && member == "__id__" {
            let xt = self.extract_type_expr(expr);
            if let Some(c) = self.realize(xt)? {
                let cc = types.get_class(c).unwrap();
                let ir = self.make_ir_type(cc)?;
                if let Some(m) = self.cache.module.clone() {
                    if let Some(ri) = m.borrow_mut().ty_mut(ir).runtime_info.as_mut() {
                        ri.value_accessed = true;
                    }
                }
                let id = self.get_class_realization(c).map(|r| r.borrow().id).unwrap_or(0);
                let i = self.n_expr(IntExpr::new(id as i64));
                return Ok((self.wrap_side(has_side, expr, i, pc)?, true));
            }
            return Ok((None, true));
        }

        // Ensure that the type is known (otherwise wait until it becomes known)
        let Some(typ) = self.extract_class_type_expr(expr) else { return Ok((None, true)) };

        // Check if this is a method or member access
        let methods = self.find_method(Some(typ), member)?;
        if methods.is_empty() {
            return self.get_class_member(expr, member, ty);
        }

        let method_ast = types.func_ast_id(methods[0]);
        let is_property = self.ast()[method_ast].attrs.has(Attr::Property);
        let is_static = self.ast()[method_ast].attrs.has(Attr::StaticMethod);
        // If a method is ambiguous use dispatch
        let best = if methods.len() > 1 {
            let root = self.get_root_name(methods[0]);
            self.get_dispatch(&root)?.expect("no dispatch")
        } else {
            methods[0]
        };
        let mut e = self.id_n(&types.func_name(best));
        let it = self.instantiate_type(best, Some(typ))?;
        self.set_type(e, it);
        if pc {
            self.ast_mut()[e].attrs.set(Attr::ExprDoNotRealize);
        }

        if is_type || is_static {
            // Static access: cls.method or obj.static_method.
            // A saved lookup with side effects needs a runtime value,
            // not an unresolved function identifier.
            if !pc && has_side {
                let el = self.n_expr(EllipsisExpr { mode: EllipsisType::Partial });
                e = self.call_n(e, vec![el]);
            }
            return Ok((self.wrap_side(has_side, expr, e, pc)?, true));
        }

        if let (Some(call), false) = (call, is_property) {
            // Instance access: `obj.method` from the call
            // Modify the call to push `self` to the front of the argument list.
            // Avoids creating partial functions.
            let a = self.ast().call_arg("", Some(expr));
            let c = &mut self.ast_mut()[call];
            c.kind.as_call_mut().unwrap().items.insert(0, a);
            c.attrs.set_int(Attr::ExprVirtual, -1);
            Ok((self.transform(Some(e))?, true))
        } else {
            // Instance access: `obj.method`
            // Transform y.method to a partial call `type(y).method(y, ...)`
            let mut method_args = vec![expr];
            // If a method is marked with @property, just call it directly
            if !is_property {
                method_args.push(self.n_expr(EllipsisExpr { mode: EllipsisType::Partial }));
            }
            let c = self.call_n(e, method_args);
            if !is_property {
                self.ast_mut()[c].attrs.set_int(Attr::ExprVirtual, -1);
            }
            Ok((self.transform(Some(c))?, true))
        }
    }

    /// `getImport(chain)` (access.cpp overload): check if a chain (a.b.c.d...) contains an
    /// import or a class prefix.
    /// PORT-NOTE: renamed from `getImport` to avoid clashing with `getImport(string)`.
    pub fn get_import_chain(&mut self, chain: &[String]) -> Result<(usize, Option<ItemRef>)> {
        let types = self.types();
        let mut import_end = 0usize;
        let mut import_name = String::new();

        // 1. Find the longest prefix that corresponds to the existing import
        //    (e.g., `a.b.c.d` -> `a.b.c` if there is `import a.b.c`)
        let mut val: Option<ItemRef> = None;
        let mut import_val: Option<ItemRef> = None;
        for i in (0..chain.len()).rev() {
            let name = chain[..=i].join("/");
            val = self.find(&name, self.get_time());
            if let Some(v) = &val {
                let (ty, n) = {
                    let b = v.borrow();
                    (b.ty, b.canonical_name.clone())
                };
                if ty.is_some_and(|t| types.is(t, "Import")) && n.starts_with("%_import_") {
                    import_name = self.get_str_literal(ty.unwrap(), 0);
                    import_end = i + 1;
                    import_val = val.clone();
                    break;
                }
            }
        }

        // Case: the whole chain is import itself
        if import_end == chain.len() {
            return Ok((import_end, val));
        }

        // Find the longest prefix that corresponds to the existing class
        // (e.g., `a.b.c` -> `a.b` if there is `class a: class b:`)
        let mut item_name = String::new();
        let mut item_end = 0usize;
        let mut ictx = if import_name.is_empty() {
            self.ctx.clone()
        } else {
            self.get_import(&import_name).ctx.clone().expect("import without ctx")
        };
        let mut i = chain.len();
        while i > import_end {
            i -= 1;
            let imodule = ictx.borrow().module().to_string();
            if imodule == "std.python" && import_end < chain.len() {
                // Special case: importing from Python.
                // Fake TypecheckItem that indicates std.python access
                let level = ictx.borrow().typecheck_level;
                let u = self.instantiate_unbound_at(self.src, level);
                let v = TypecheckItem::new("", "", &imodule, Some(u), 0).into_ref();
                return Ok((import_end, Some(v)));
            }
            let key = chain[import_end..=i].join(".");
            // check only globals for imports!
            val = TypeContext::find_in(self.cache, &ictx, &key, 0, if import_name.is_empty() { None } else { Some("") });
            let info = val.as_ref().map(|v| {
                let b = v.borrow();
                (b.ty, b.canonical_name.clone(), b.is_func(&types), b.is_type(&types), b.is_conditional())
            });
            if let Some((Some(vt), vn, _, _, _)) = &info {
                if i + 1 != chain.len() && types.is(*vt, "Import") && vn.starts_with("%_import_") {
                    import_name = self.get_str_literal(*vt, 0);
                    import_end = i + 1;
                    import_val = val.clone();
                    ictx = self.get_import(&import_name).ctx.clone().expect("import without ctx");
                    i = chain.len();
                    continue;
                }
            }
            let is_overload = info.as_ref().is_some_and(|(_, vn, is_func, _, _)| *is_func && self.has_overloads(vn));
            if is_overload && import_end == i {
                // top-level overload
                item_name = info.unwrap().1;
                item_end = i + 1;
                break;
            }
            // Class member
            if let Some((_, vn, _, is_type, is_cond)) = &info {
                if !is_overload && (import_name.is_empty() || *is_type || !*is_cond) {
                    item_name = vn.clone();
                    item_end = i + 1;
                    break;
                }
            }
            // Resolve the identifier from the import
            if let Some(imp) = self.find("Import", 0) {
                let it = imp.borrow().ty();
                if let Some(t) = self.extract_class_type(it) {
                    if self.find_member(t, &key).is_some() {
                        return Ok((import_end, import_val));
                    }
                    if !self.find_method(Some(t), &key)?.is_empty() {
                        return Ok((import_end, import_val));
                    }
                }
            }
        }
        if item_name.is_empty() && import_name.is_empty() {
            if self.ctx.borrow().base_ref().py_captures.is_some() {
                return Ok((1, None));
            }
            typhon_common::bail_e!(ErrorKind::IMPORT_NO_MODULE, self.src, chain[import_end]);
        } else if item_name.is_empty() {
            let (imp_ctx, imp_name) = {
                let imp = self.get_import(&import_name);
                (imp.ctx.clone().expect("import without ctx"), imp.name.clone())
            };
            if !self.ctx.borrow().is_stdlib_loading && import_name.ends_with("__init__.codon") {
                // Special case: subimport is not yet loaded
                //   (e.g., import a; a.b.x where a.b is a module as well)
                if super::helpers::get_import_file(self.cache, &chain[import_end], &import_name, false).is_some() {
                    // Auto-load support
                    let w = self.id_n(&chain[import_end]);
                    let is = self.n_stmt(ImportStmt { from: Some(w), ..Default::default() });
                    let s = self.n_stmt(SuiteStmt { items: vec![is] });
                    if let Some(sc) = self.cache.hooks.scoping.clone() {
                        sc(self.cache, s, None)?;
                    }
                    let pre = self.preamble;
                    let s = {
                        let mut v = TypecheckVisitor::new(self.cache, imp_ctx, Some(pre), None);
                        v.tr_stmt(s)?
                    };
                    self.prepend_stmts.borrow_mut().push(s);
                    return self.get_import_chain(chain);
                }
            }
            typhon_common::bail_e!(ErrorKind::IMPORT_NO_NAME, self.src, chain[import_end], imp_name);
        }
        Ok((item_end, val))
    }

    /// `getDispatch(fn)`: find or generate an overload dispatch function for a given
    /// overload. Dispatch functions ensure that a function call is being routed to the
    /// correct overload even when dealing with partial functions and decorators.
    ///   `def foo:dispatch(*args, **kwargs): return foo(*args, **kwargs)`
    pub fn get_dispatch(&mut self, f: &str) -> Result<Option<TypeId>> {
        let overloads = self.cache.overloads.get(f).cloned().unwrap_or_default();

        // Single overload: just return it
        if overloads.len() == 1 {
            let t = self.force_find(&overloads[0]).borrow().ty();
            return Ok(self.cache.types.get_func(t));
        }
        // Check if dispatch exists
        for m in &overloads {
            let fu = self.get_function_name(m).cloned();
            if let Some(fu) = fu {
                if self.is_dispatch_ast(fu.ast) {
                    return Ok(fu.ty);
                }
            }
        }

        // Dispatch does not exist. Generate it
        let name = format!("{f}{FN_DISPATCH_SUFFIX}");
        let ofn = self.get_function_name(&overloads[0]).cloned().expect("bad overload");
        let ofn_ast = ofn.ast.expect("overload without ast");
        let aa = self.ast()[ofn_ast].attrs.get_str(Attr::ParentClass).map(|s| s.to_string());
        let unm = self.get_unmangled_name(f);
        let mut root = match &aa {
            Some(a) => {
                let i = self.id_n(a);
                self.dot_n(i, &unm)
            }
            None => self.id_n(f),
        };
        let a = self.id_n("args");
        let sa = self.n_expr(crate::ast::StarExpr { expr: Some(a) });
        let k = self.id_n("kwargs");
        let sk = self.n_expr(crate::ast::KeywordStarExpr { expr: Some(k) });
        root = self.n_expr(CallExpr {
            expr: Some(root),
            items: vec![CallArg::new("", Some(sa)), CallArg::new("", Some(sk))],
            ordered: false,
            partial: false,
        });
        let ctx = self.ctx.clone();
        let nar = ctx.borrow().generate_canonical_name(self.cache, "args", false, false);
        let nkw = ctx.borrow().generate_canonical_name(self.cache, "kwargs", false, false);
        let src = self.src;
        let params = vec![
            self.ast().new_param(src, format!("*{nar}"), None, None, 0, ParamKind::Normal),
            self.ast().new_param(src, format!("**{nkw}"), None, None, 0, ParamKind::Normal),
        ];
        let ret = self.n_stmt(ReturnStmt { expr: Some(root) });
        let suite = self.n_stmt(SuiteStmt { items: vec![ret] });
        let ast = self.ast_mut().new_function(src, name.clone(), None, params, Some(suite), vec![], false)?;
        let mpath = self.ctx.borrow().module_info().path.clone();
        {
            let at = &mut self.ast_mut()[ast].attrs;
            at.set(Attr::AutoGenerated);
            at.set_str(Attr::Module, mpath);
            if let Some(a) = &aa {
                at.set_str(Attr::ParentClass, a.clone());
            }
        }
        self.cache.set_reverse(name.clone(), unm);

        self.prepare_call_layout(ast);
        self.register_func_ast(ast);
        let base_type = self.get_func_type_base(2)?;
        let types = self.types();
        // Make sure that parent is set so that the parent type can be passed to the inner
        // call (e.g., A[B].foo -> A.foo.dispatch() { A[B].foo() })
        let parent = ofn.ty.and_then(|t| types.func_parent(t));
        let typ = types.new_func(base_type, ast, vec![], parent);
        let level = self.ctx.borrow().typecheck_level;
        let typ = types.generalize(typ, level - 1);
        TypeContext::add_func(self.cache, &self.ctx, &name, &name, typ, src);

        self.cache.overloads.entry(f.to_string()).or_default().insert(0, name.clone());
        self.cache.functions.insert(
            name,
            Function { module: String::new(), root_name: f.to_string(), ast: Some(ast), ty: Some(typ), ..Default::default() },
        );
        self.set_done_stmt(ast);
        Ok(Some(typ))
    }

    fn wrap_side2(&mut self, has_side: bool, expr: ExprId, e: ExprId) -> Result<Option<ExprId>> {
        if has_side {
            let s = self.n_stmt(ExprStmt { expr: Some(expr) });
            let se = self.n_expr(StmtExpr { items: vec![s], expr: Some(e) });
            return self.transform(Some(se));
        }
        self.transform(Some(e))
    }

    /// `getClassMember(expr, member, type)`: find a class member.
    ///   `obj.GENERIC` -> `GENERIC`, `optional.member` -> `unwrap(optional).member`,
    ///   `pyobj.member` -> `pyobj._getattr("member")`.
    pub fn get_class_member(&mut self, expr: ExprId, member: &str, ty: Option<TypeId>) -> Result<(Option<ExprId>, bool)> {
        let types = self.types();
        let st = stdlib();
        let typ = self.extract_class_type_expr(expr);
        typhon_common::seqassert!(typ.is_some(), "not a class");
        let typ = typ.unwrap();

        // Case: object member access (`obj.member`)
        if !Self::is_type_expr(self.cache, expr) {
            if let Some(m) = self.find_member(typ, member) {
                if let Some(t) = ty {
                    let it = self.instantiate_type(m.ty.expect("member without type"), Some(typ))?;
                    self.unify(t, it)?;
                }
                if let (Some(t), Some(te)) = (ty, m.type_expr) {
                    if !types.can_realize(t) {
                        let r = self.with_class_generics(typ, false, false, false, |v| {
                            let c = v.cache.ast.clone_expr(te, true);
                            v.tr(c)
                        })?;
                        let x = self.extract_type_expr(r);
                        self.unify(t, x)?;
                    }
                }
                return Ok((None, true));
            }
        }

        let has_side = self.has_side_effect(expr);

        // Case: class variable (`Cls.var`)
        let var = self.cache.get_class_by_type(typ).and_then(|c| c.class_vars.get(member).cloned());
        if let Some(var) = var {
            let i = self.id_n(&var);
            return Ok((self.wrap_side2(has_side, expr, i)?, true));
        }

        // Case: special members
        let special = match member {
            "__elemsize__" => Some("int"),
            "__atomic__" | "__contents_atomic__" => Some("bool"),
            _ => None,
        };
        if let Some(m) = special {
            if let Some(t) = ty {
                let s = self.get_stdlib_type(m)?;
                self.unify(t, s)?;
            }
            return Ok((None, true));
        }
        if member == "__name__" && Self::is_type_expr(self.cache, expr) {
            if let Some(t) = ty {
                let s = self.get_stdlib_type(&st.string)?;
                self.unify(t, s)?;
            }
            return Ok((None, true));
        }

        // Case: object generic access (`obj.T`)
        let generic = types.generics(typ).into_iter().find(|g| member == self.get_unmangled_name(&g.name));
        if let Some(g) = generic {
            if g.static_kind != LiteralKind::Runtime {
                if let Some(t) = ty {
                    self.unify(t, g.ty())?;
                }
                if self.realize(g.ty())?.is_some() {
                    let s = types.static_expr(g.ty(), &mut self.cache.ast).expect("not a static");
                    return Ok((self.wrap_side2(has_side, expr, s)?, true));
                }
            } else {
                let mut payload = g.ty();
                if types.is(typ, &st.unrealized_type) {
                    payload = self.instantiate_type(payload, None)?;
                }
                let t = self.instantiate_type_var(payload)?;
                if let Some(tt) = ty {
                    self.unify(tt, t)?;
                }
                if self.realize(t)?.is_some() {
                    let i = self.id_n(&types.realized_name(payload));
                    return Ok((self.wrap_side2(has_side, expr, i)?, true));
                }
            }
            return Ok((None, true));
        }

        // Case: transform `optional.member` to `unwrap(optional).member`
        if types.is(typ, &st.optional) {
            let f = self.id_n(&mangle::mangled_method("", "Optional", "__unwrap__", 0, 0));
            let c = self.call_n(f, vec![expr]);
            let d = self.dot_n(c, member);
            return Ok((self.transform(Some(d))?, true));
        }

        // Case: transform `pyobj.member` to `pyobj._getattr("member")`
        if types.is(typ, "pyobj") {
            let d = self.dot_n(expr, "_getattr");
            let s = self.n_expr(StringExpr::new(member, ""));
            let c = self.call_n(d, vec![s]);
            return Ok((self.transform(Some(c))?, true));
        }

        // Case: NamedTuple support
        if types.is(typ, &st.named_tuple) {
            let id = self.get_int_literal(typ, 0);
            let names = types.generated_tuple_names.borrow();
            typhon_common::seqassert!(id >= 0 && (id as usize) < names.len(), "bad id: {}", id);
            let names = names[id as usize].clone();
            if let Some(i) = names.iter().position(|n| n == member) {
                let d = self.dot_n(expr, "args");
                let n = self.n_expr(IntExpr::new(i as i64));
                let ix = self.n_expr(IndexExpr { expr: Some(d), index: Some(n) });
                return Ok((self.transform(Some(ix))?, true));
            }
        }

        // Case: __getattr__ support. Ensure that only Literal[str] arguments are accepted.
        let u = self.instantiate_unbound();
        types.with_link_mut(u, |l| l.static_kind = LiteralKind::String);
        if let Some(m) = self.find_best_method_types(typ, "__getattr__", &[typ, u])? {
            let fg = types.func_generics(m);
            let non_self = fg.iter().filter(|g| self.get_unmangled_name(&g.name) != "Self").count();
            if non_self == 1 && fg.iter().any(|g| types.static_kind(g.ty()) == LiteralKind::String) {
                let d = self.dot_n(expr, "__getattr__");
                let s = self.n_expr(StringExpr::new(member, ""));
                let c = self.call_n(d, vec![s]);
                return Ok((self.transform(Some(c))?, true));
            }
        }

        // Case: name has an alternative identifier with more precise type. Use it.
        if let Some(ei) = self.ast()[expr].kind.as_id().map(|i| i.value.clone()) {
            let alt = self.find(&ei, 0).and_then(|v| v.borrow().alternative.clone());
            if let Some(alt) = alt {
                let n = alt.borrow().canonical_name.clone();
                let i = self.id_n(&n);
                let d = self.dot_n(i, member);
                return Ok((self.transform(Some(d))?, true));
            }
        }

        // For debugging purposes:
        Ok((None, false))
    }
}

