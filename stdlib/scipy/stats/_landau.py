def _poly(c: List[float], x: float) -> float:
    r = 0.0
    i = len(c) - 1
    while i >= 0:
        r = r * x + c[i]
        i -= 1
    return r

def _rat(tab: List[List[float]], k: int, t: float) -> float:
    return _poly(tab[2 * k], t) / _poly(tab[2 * k + 1], t)

def _il(x: float) -> int:
    return int(ilogb(x))

def _ldx(x: float, n: int) -> float:
    return ldexp(x, i32(n))

def _pdf_plus(x: float) -> float:
    T = _TAB_PDF_PLUS
    if x < 1:
        return _rat(T, 0, x)
    if x < 2:
        return _rat(T, 1, x - 1)
    if x < 4:
        return _rat(T, 2, x - 2)
    if x < 8:
        return _rat(T, 3, x - 4)
    if x < 16:
        return _rat(T, 4, x - 8)
    if x < 32:
        return _rat(T, 5, x - 16)
    if x < 64:
        return _rat(T, 6, x - 32)
    if _il(x) < 8:
        return _poly(T[14], log2(_ldx(x, -6))) / (_poly(T[15], log2(_ldx(x, -6))) * x * x)
    if _il(x) < 16:
        return _poly(T[16], log2(_ldx(x, -8))) / (_poly(T[17], log2(_ldx(x, -8))) * x * x)
    if _il(x) < 32:
        return _poly(T[18], log2(_ldx(x, -16))) / (_poly(T[19], log2(_ldx(x, -16))) * x * x)
    if _il(x) < 64:
        return _poly(T[20], log2(_ldx(x, -32))) / (_poly(T[21], log2(_ldx(x, -32))) * x * x)
    return 2 / (_PI * x * x)

def _pdf_minus(x: float) -> float:
    T = _TAB_PDF_MINUS
    if x >= -1:
        return _rat(T, 0, x + 1)
    if x >= -2:
        return _rat(T, 1, x + 2)
    sigma = exp(-x * _PI / 2 - _LAMBDA_BIAS)
    s = exp(-sigma) * sqrt(sigma)
    if x >= -4:
        return s * _rat(T, 2, -x - 2)
    if x >= -5.1328125:
        return s * _rat(T, 3, -x - 4)
    return 0.0

