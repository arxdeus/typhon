def _quantile(p: float, complement: bool) -> float:
    if p > 0.5:
        return _q_upper(1 - p) if not complement else _q_lower(1 - p)
    return _q_upper(p) if complement else _q_lower(p)

def landau_pdf(x: float) -> float:
    if x >= 0:
        return _pdf_plus(x)
    elif x <= 0:
        return _pdf_minus(x)
    return K.NAN

def _cdf_imp(x: float, complement: bool) -> float:
    if x >= 0:
        return _cdf_plus(x) if complement else 1 - _cdf_plus(x)
    elif x <= 0:
        return 1 - _cdf_minus(x) if complement else _cdf_minus(x)
    return K.NAN

def landau_cdf(x: float) -> float: return _cdf_imp(x, False)
def landau_sf(x: float) -> float: return _cdf_imp(x, True)

def landau_ppf(p: float) -> float:
    if not (p >= 0 and p <= 1):
        return K.NAN
    if p == 0:
        return -K.INF
    if p == 1:
        return K.INF
    return _quantile(p, False)

def landau_isf(p: float) -> float:
    if not (p >= 0 and p <= 1):
        return K.NAN
    if p == 0:
        return K.INF
    if p == 1:
        return -K.INF
    return _quantile(p, True)
