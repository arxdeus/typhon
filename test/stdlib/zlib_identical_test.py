import zlib
def gen(n: int, seed: int) -> bytes:
    x = seed
    out = List[int]()
    words = [b"alpha", b"beta", b"gamma", b"delta", b"epsilon", b" ", b"\n", b"zz"]
    while len(out) < n:
        x = (x * 1103515245 + 12345) & 0x7fffffff
        w = words[(x >> 8) % 8]
        for c in w:
            out.append(int(c))
        if (x >> 4) % 7 == 0:
            out.append((x >> 12) & 255)
    return bytes(out[:n])

