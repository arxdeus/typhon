import hashlib

def _msg(L: int) -> str:
    return "".join([chr(97 + (i * 7) % 26) for i in range(L)])

@test
def test_hashlib_vectors():
    for k, v in EXPECTED.items():
        name, L = k
        assert hashlib.new(name, _msg(L).encode()).hexdigest() == v
        # chunked updates must agree
        h = hashlib.new(name)
        m = _msg(L).encode()
        i = 0
        while i < len(m):
            h.update(m[i:i + 37])
            i += 37
        assert h.hexdigest() == v

@test
def test_hashlib_api():
    h = hashlib.md5()
    h.update(b"ab")
    h2 = h.copy()
    h.update("c")
    assert h.hexdigest() == "900150983cd24fb0d6963f7d28e17f72"
    assert h2.hexdigest() == "187ef4436122d1cc2f40dc2b92f0eba0"
    assert h.name == "md5" and h.digest_size == 16 and h.block_size == 64
    assert hashlib.sha512().block_size == 128
    assert hashlib.sha256(b"abc").digest().hex() == "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
    assert hashlib.md5("a,b\n1,2\n".encode()).hexdigest() == hashlib.new("MD5", b"a,b\n1,2\n").hexdigest()

test_hashlib_vectors()
test_hashlib_api()
