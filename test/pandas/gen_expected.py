"""Reference values for test/pandas/*.py, generated with CPython pandas.

Run: /path/to/venv/bin/python test/pandas/gen_expected.py
Prints Typhon literal assignments that are pasted into the .py tests.
Inputs are deterministic (integer LCG plus exact IEEE operations), so the
same data is rebuilt bit-for-bit inside the Typhon tests.
"""
import io
import hashlib
import numpy as np
import pandas as pd


def make_F(n, m, seed=12345):
    F = np.empty((n, m))
    s = seed
    for i in range(n):
        for j in range(m):
            s = (s * 1103515245 + 12345) % 2147483648
            F[i, j] = (s % 20001 - 10000) * 0.000123 * (j + 1)
    return F


def make_y(n):
    return np.array([(i * 7 % 5) % 2 for i in range(n)], dtype=np.int64)


def lit(name, v):
    if isinstance(v, str):
        print(f"{name} = {v!r}")
    elif isinstance(v, float):
        print(f"{name} = {v!r}")
    elif isinstance(v, (list, tuple)):
        print(f"{name} = {[x.item() if hasattr(x, 'item') else x for x in v]!r}")
    else:
        print(f"{name} = {v!r}")


