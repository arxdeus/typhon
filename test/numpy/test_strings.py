# Tests for numpy.strings / numpy.char (expected values from numpy 2.5.4).
import numpy as np

a = np.array(['  Hello World ', 'abc123', 'x\ty', 'TITLE Case', ''])
b = np.array(['ab', 'aB', 'zz'])

def check(name: str, got, exp):
    if got != exp:
        print('TEST FAILED', name, got, exp)

check('upper', np.strings.upper(a).tolist(), ['  HELLO WORLD ', 'ABC123', 'X\tY', 'TITLE CASE', ''])
check('lower', np.strings.lower(a).tolist(), ['  hello world ', 'abc123', 'x\ty', 'title case', ''])
check('swapcase', np.strings.swapcase(b).tolist(), ['AB', 'Ab', 'ZZ'])
check('capitalize', np.strings.capitalize(b).tolist(), ['Ab', 'Ab', 'Zz'])
check('title', np.strings.title(a).tolist(), ['  Hello World ', 'Abc123', 'X\tY', 'Title Case', ''])
check('str_len', np.strings.str_len(a).tolist(), [14, 6, 3, 10, 0])
check('isalpha', np.strings.isalpha(b).tolist(), [True, True, True])
check('isdigit', np.strings.isdigit(np.array(['12', 'a1'])).tolist(), [True, False])
check('isalnum', np.strings.isalnum(a).tolist(), [False, True, False, False, False])
check('isupper', np.strings.isupper(b).tolist(), [False, False, False])
check('islower', np.strings.islower(b).tolist(), [True, False, True])
check('isspace', np.strings.isspace(np.array([' ', 'a ', ''])).tolist(), [True, False, False])
check('istitle', np.strings.istitle(a).tolist(), [True, False, False, False, False])
check('strip', np.strings.strip(a).tolist(), ['Hello World', 'abc123', 'x\ty', 'TITLE Case', ''])
check('lstrip', np.strings.lstrip(b, 'a').tolist(), ['b', 'B', 'zz'])
check('rstrip', np.strings.rstrip(b, 'zB').tolist(), ['ab', 'a', ''])
check('center', np.strings.center(b, 6, '*').tolist(), ['**ab**', '**aB**', '**zz**'])
check('ljust', np.strings.ljust(b, 4).tolist(), ['ab  ', 'aB  ', 'zz  '])
check('rjust', np.strings.rjust(b, 3, '-').tolist(), ['-ab', '-aB', '-zz'])
check('zfill', np.strings.zfill(np.array(['-5', '42']), 4).tolist(), ['-005', '0042'])
check('expandtabs', np.strings.expandtabs(a, 4).tolist()[2], 'x   y')
check('find', np.strings.find(a, 'l').tolist(), [4, -1, -1, -1, -1])
check('rfind', np.strings.rfind(a, 'l').tolist(), [11, -1, -1, -1, -1])
check('count', np.strings.count(a, 'l').tolist(), [3, 0, 0, 0, 0])
check('count2', np.strings.count(a, 'l', 0, 5).tolist(), [1, 0, 0, 0, 0])
check('startswith', np.strings.startswith(b, 'a').tolist(), [True, True, False])
check('endswith', np.strings.endswith(b, 'z').tolist(), [False, False, True])
check('find_neg', np.strings.find(b, 'b', -1).tolist(), [1, -1, -1])
check('replace', np.strings.replace(a, 'l', 'L', 2).tolist()[0], '  HeLLo World ')
check('multiply', np.strings.multiply(b, 2).tolist(), ['abab', 'aBaB', 'zzzz'])
check('add', np.strings.add(b, '!').tolist(), ['ab!', 'aB!', 'zz!'])
check('equal', np.strings.equal(b, np.array(['ab', 'ab', 'zz'])).tolist(), [True, False, True])
check('less', np.strings.less(b, 'b').tolist(), [True, True, False])
check('greater_equal', np.strings.greater_equal(b, 'aB').tolist(), [True, True, True])
check('slice', np.strings.slice(b, 1).tolist(), ['a', 'a', 'z'])
check('slice3', np.strings.slice(a, 2, None, 2).tolist()[0], 'HloWrd')
p0, p1, p2 = np.strings.partition(np.array(['a=b=c', 'xy']), '=')
check('partition', [p0.tolist(), p1.tolist(), p2.tolist()], [['a', 'xy'], ['=', ''], ['b=c', '']])
r0, r1, r2 = np.strings.rpartition(np.array(['a=b=c', 'xy']), '=')
check('rpartition', [r0.tolist(), r1.tolist(), r2.tolist()], [['a=b', ''], ['=', ''], ['c', 'xy']])
m = np.array([['ab', 'c'], ['de', 'fgh']])
check('2d', np.strings.str_len(m).tolist(), [[2, 1], [2, 3]])
try:
    np.strings.index(b, 'a')
    print('TEST FAILED index should raise')
except ValueError:
    pass
check('char.split', np.char.split(np.array(['a b', 'c,d']), ',').tolist(), [['a b'], ['c', 'd']])
check('char.split_ws', np.char.split(np.array(['a  b c']), None, 1).tolist(), [['a', 'b c']])
check('char.rsplit', np.char.rsplit(np.array(['a,b,c']), ',', 1).tolist(), [['a,b', 'c']])
check('char.join', np.char.join('-', np.array(['abc', 'de'])).tolist(), ['a-b-c', 'd-e'])
check('char.upper', np.char.upper(b).tolist(), ['AB', 'AB', 'ZZ'])
check('char.cmp', np.char.compare_chararrays(np.array(['a ', 'b']), np.array(['a', 'a']), '==', True).tolist(), [True, False])
print('strings done')
