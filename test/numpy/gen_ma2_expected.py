def L(v):
    if isinstance(v, (list, tuple)):
        out = []
        for t in v:
            out.extend(L(t))
        return out
    if isinstance(v, np.ndarray) and not isinstance(v, ma.MaskedArray):
        return [float(t) for t in v.astype(float).ravel()]
    if isinstance(v, ma.MaskedArray):
        return [float(t) for t in np.asarray(v.filled(0)).astype(float).ravel()]
    return [float(v)]

def M(v):
    if isinstance(v, ma.MaskedArray):
        return [bool(t) for t in np.ma.getmaskarray(v).ravel()]
    return []

