# Generates test/mne/test_decoding_xdawn.py (expected values from mne 1.13.2).
import warnings
import numpy as np
import mne
from mne.decoding import XdawnTransformer, CSP, SpatialFilter, get_spatial_filter_from_estimator, TimeFrequency
warnings.simplefilter("ignore")
mne.set_log_level("ERROR")
out = []
def rec(n, v): out.append((n, [float(x) for x in np.asarray(v, dtype=float).ravel()]))
rng = np.random.RandomState(3)
n_ep, n_ch, n_t = 30, 5, 60
y = np.arange(n_ep) % 3
X = rng.randn(n_ep, n_ch, n_t)
mix = rng.randn(n_ch, n_ch)
for e in range(n_ep):
    X[e] = mix @ X[e]
    X[e, :, 10:20] += (y[e] + 1) * np.outer(rng.randn(n_ch) * 0 + np.arange(1, n_ch + 1), np.hanning(10))
for name, kw in [('x1', dict()), ('x2', dict(n_components=3, reg=0.1)), ('x3', dict(restr_type='restricting', n_components=2))]:
    t = XdawnTransformer(**kw).fit(X, y)
    rec(name + '_f', t.filters_); rec(name + '_p', t.patterns_); rec(name + '_e', t.evals_)
    Z = t.transform(X); rec(name + '_t', Z[:2]); rec(name + '_inv', t.inverse_transform(Z)[:2])
t = XdawnTransformer(2).fit(X)
rec('xnoy_f', t.filters_)
y2 = (np.arange(n_ep) % 2)
info = mne.create_info(n_ch, 100., 'eeg')
csp = CSP(n_components=3, reg=None, log=True).fit(X, y2)
sf = get_spatial_filter_from_estimator(csp, info)
rec('sf_f', sf.filters); rec('sf_p', sf.patterns); rec('sf_e', sf.evals)
sf2 = SpatialFilter(info, np.asarray(csp.filters_[:3]))
rec('sf2_p', sf2.patterns)
tf = TimeFrequency(freqs=[8., 12., 20.], sfreq=100., method='morlet', n_cycles=3., output='power')
rec('tf_pow', tf.fit_transform(X[:3]))
tf = TimeFrequency(freqs=[8., 12.], sfreq=100., method='morlet', n_cycles=3., output='complex', decim=2)
r = tf.fit_transform(X[:2]); rec('tf_re', r.real); rec('tf_im', r.imag)
tf = TimeFrequency(freqs=[8., 12.], sfreq=100., method='multitaper', n_cycles=3., output='power', time_bandwidth=4.)
rec('tf_mt', tf.fit_transform(X[:2]))
for tpl, outf, pred in [('test_decoding_xdawn', 'test_decoding_xdawn', lambda n: not n.startswith('tf_')),
                         ('test_decoding_tf', 'test_decoding_tf', lambda n: n.startswith('tf_'))]:
    src = open('test/mne/templates/%s.tpl' % tpl).read()
    exp = "EXPECTED = [\n" + "".join("    (%r, %r),\n" % (n, v) for n, v in out if pred(n)) + "]\n"
    open('test/mne/%s.py' % outf, 'w').write("# Generated by gen_xdawn_sf_expected.py from templates/%s.tpl (mne 1.13.2)\n" % tpl + src.replace("#EXPECTED#", exp))
