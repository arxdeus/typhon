# ---- BCI2000 ----
def bci_file(fname, fmt, dt):
    nch, ns, svl = 3, 40, 2
    sig = rng.randint(-1000, 1000, size=(nch, ns)).astype(dt)
    stim = (np.arange(ns) % 9) * 3
    body = b""
    for s in range(ns):
        body += sig[:, s].astype("<" + np.dtype(dt).str[1:]).tobytes()
        sv = [0, 0]
        v = int(stim[s]) << 2  # bitPos 2, length 8
        sv[0] = v & 255; sv[1] = (v >> 8) & 255
        body += bytes(sv)
    def head(n):
        t = f"HeaderLen= {n:6d} SourceCh= {nch} StatevectorLen= {svl} DataFormat= {fmt}\r\n"
        t += "[ State Vector Definition ]\r\nStimulusCode 8 0 0 2\r\nRunning 1 0 1 0\r\n"
        t += "[ Parameter Definition ]\r\nSource:Signal%20Properties:DataIOFilter int SamplingRate= 100Hz // rate\r\n\r\n"
        return t.encode()
    n = len(head(0)); hb = head(n)
    open(fname, "wb").write(hb + body)
for f, dt in (("int16", np.int16), ("int32", np.int32), ("float32", np.float32)):
    bci_file(os.path.join(D, f"test_bci2k_{f}.dat"), f, dt)

