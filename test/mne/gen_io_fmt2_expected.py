# Writes fixtures (EGI simple binary, Neuroscan CNT, BCI2000, BESA avr/mul, NEDF) under test/mne/data/
# and generates test_io_egi_bci_besa.py, test_io_cnt.py and test_io_nedf.py using mne 1.13.2 as the
# reference (NEDF expected values are computed analytically since defusedxml is not installed).
