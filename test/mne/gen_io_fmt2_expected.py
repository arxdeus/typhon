# ---- CNT ----
def cnt_file(fname, nch, ns, nbytes, ch_off, events):
    hdr = bytearray(900)
    def put(off, b): hdr[off:off + len(b)] = b
    put(21, b"123"); put(121, b"Doe John"); put(205, b"sess1"); put(225, b"03/04/20"); put(235, b"10:20:30")
    put(370, struct.pack("<H", nch)); put(376, struct.pack("<H", 250))
    hdr[438] = 1; hdr[439] = 1; put(402, struct.pack("<hh", 3, -1))
    put(864, struct.pack("<i", ns)); put(869, struct.pack("<f", 0.5)); put(875, struct.pack("<f", 70.0))
    ev_pos = 900 + 75 * nch + nch * ns * nbytes
    put(886, struct.pack("<i", ev_pos)); put(890, struct.pack("<f", ns / 250.0)); put(894, struct.pack("<i", ch_off * nbytes if ch_off > 1 else 0))
    names = ["Fz", "Cz", "Pz", "EOG"][:nch]
    chs = b""
    for i, nm in enumerate(names):
        c = bytearray(75)
        c[0:len(nm)] = nm.encode()
        if nm == "Pz": c[14] = 1
        ang = 2 * np.pi * i / nch
        c[19:27] = struct.pack("<ff", float(np.cos(ang)) * 10 + 1, float(np.sin(ang)) * 10 + 2)
        c[47:49] = struct.pack("<h", 3 * i)
        c[59:63] = struct.pack("<f", 2.0 + i); c[71:75] = struct.pack("<f", 1.5)
        chs += bytes(c)
    dt = "<i2" if nbytes == 2 else "<i4"
    data = rng.randint(-3000, 3000, size=(nch, ns))
    body = b""
    for ci in range(0, ns, ch_off):
        for c in range(nch):
            body += data[c, ci:ci + ch_off].astype(dt).tobytes()
    tbl = struct.pack("<Bll", 1, 8 * len(events), 0)
    tbl += b"\0" * 0
    evb = b""
    for (stim, kb, kp, samp) in events:
        evb += struct.pack("<HBBl", stim, kb, kp, 900 + 75 * nch + (samp + 1) * nch * nbytes)
    open(fname, "wb").write(bytes(hdr) + chs + body + tbl + evb)
