# Generates test/mne/test_layout.py (expected values from mne 1.13.2).
import warnings
import numpy as np
import mne
warnings.simplefilter("ignore")
mne.set_log_level("ERROR")
out = []
def rec(name, v):
    out.append((name, [float(x) for x in np.asarray(v, dtype=float).ravel()]))

NAMES = ['Fp1', 'Fp2', 'F7', 'F3', 'Fz', 'F4', 'F8', 'T7', 'C3', 'Cz', 'C4', 'T8',
         'P7', 'P3', 'Pz', 'P4', 'P8', 'O1', 'O2']
for k in ['Vectorview-all', 'Vectorview-mag', 'EEG1005', 'CTF-275', 'KIT-157']:
    l = mne.channels.read_layout(k)
    rec('rl_' + k, l.pos[:3]); rec('rl_n_' + k, [len(l.names)]); rec('rl_ids_' + k, l.ids[:3])
    rec('rlbox_' + k, l.box if l.box else [0,0,0,0])
l = mne.channels.read_layout('Vectorview-all', scale=False); rec('rl_noscale', l.pos[:3])
info = mne.create_info(NAMES, 100., 'eeg')
info.set_montage('standard_1020')
l = mne.channels.make_eeg_layout(info); rec('eeg_pos', l.pos); rec('eeg_ids', l.ids)
l = mne.channels.make_eeg_layout(info, radius=0.4, width=0.1, height=0.08); rec('eeg_pos2', l.pos)
inf2 = mne.create_info(['a','b','c','d','e','f','g'], 100., 'misc')
l = mne.channels.make_grid_layout(inf2); rec('grid_pos', l.pos); rec('grid_ids', l.ids)
l = mne.channels.make_grid_layout(inf2, n_col=3); rec('grid_pos3', l.pos)
rng = np.random.RandomState(1)
xy = rng.rand(8, 2) * 10
l = mne.channels.generate_2d_layout(xy); rec('g2d_pos', l.pos); rec('g2d_box', l.box)
l = mne.channels.generate_2d_layout(xy, normalize=False, name='x'); rec('g2d_pos_n', l.pos)
l = mne.channels.find_layout(info); rec('fl_pos', l.pos)
inf3 = mne.create_info(['MEG 0111', 'MEG 0112', 'MEG 0113', 'MEG 0121'], 100., ['mag', 'grad', 'grad', 'mag'])
for c in inf3['chs']:
    c['coil_type'] = 3024 if c['kind'] == 1 and c['coil_type'] != 3012 else c['coil_type']
for i, t in enumerate(['mag', 'grad', 'grad', 'mag']):
    inf3['chs'][i]['coil_type'] = 3024 if t == 'mag' else 3012
l = mne.channels.find_layout(inf3); rec('fl_vv', l.pos); rec('fl_vv_n', [len(l.names)])
l = mne.channels.find_layout(inf3, ch_type='mag'); rec('fl_mag_n', [len(l.names)])

src = open('test/mne/templates/test_layout.tpl').read()
exp = "EXPECTED = [\n" + "".join("    (%r, %r),\n" % (n, v) for n, v in out) + "]\n"
open('test/mne/test_layout.py', 'w').write("# Generated by gen_layout_expected.py from templates/test_layout.tpl (mne 1.13.2)\n" + src.replace("#EXPECTED#", exp))
