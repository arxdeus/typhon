def emit(testname, src, g):
    fexp, sexp = [], []
    g["check"] = lambda n, got, rtol=1e-7, atol=1e-15: fexp.append((n, [float(x) for x in np.asarray(got, dtype=float).ravel()]))
    g["checks"] = lambda n, got: sexp.append((n, [str(v) for v in got]))
    g.update({"np": np, "mne": mne})
    exec(compile(src, testname, "exec"), g)
    pre = pre0.replace("@@FEXP@@", "\n".join(f"    ({n!r}, {fl(v)})," for n, v in fexp)).replace("@@SEXP@@", "\n".join(f"    ({n!r}, {v!r})," for n, v in sexp))
    open(os.path.join(HERE, testname + ".py"), "w").write("# Generated by gen_io_fmt3_expected.py (mne 1.13.2)\n" + pre + src)

