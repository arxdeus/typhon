    for blk in range(2):
        t0 = 1000 + blk * 100
        L.append(f"START\t{t0}\tLEFT\tSAMPLES\tEVENTS")
        L.append("PRESCALER\t1")
        L.append("SAMPLES\tGAZE\tLEFT\tRATE\t500.00\tTRACKING\tCR\tFILTER\t2")
        L.append("EVENTS\tGAZE\tLEFT\tRATE\t500.00\tTRACKING\tCR\tFILTER\t2")
        L.append(f"MSG\t{t0 + 3} trial_{blk}")
        for k in range(6):
            L.append(f"{t0 + 2 * k}\t{100 + k}.0\t{200 - k}.0\t{500 + k}.0\t...")
        L.append(f"EBLINK L {t0 + 2}\t{t0 + 6}\t4")
