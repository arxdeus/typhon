# ---- NSx (NEURALCD 2.2, 3 channels, 2 packets) ----
def nsx():
    nch = 3
    hdr = bytearray(314)
    hdr[0:8] = b"NEURALCD"; hdr[8] = 2; hdr[9] = 2
    struct.pack_into("<I", hdr, 10, 314 + 66 * nch)
    hdr[14:17] = b"grp"
    struct.pack_into("<II", hdr, 286, 10, 30000)
    struct.pack_into("<8H", hdr, 294, 2020, 3, 3, 4, 10, 20, 30, 250)
    struct.pack_into("<I", hdr, 310, nch)
    ext = b""
    for i, n in enumerate(["ch1", "ch2", "status"]):
        e = bytearray(66)
        e[0:2] = b"CC"; struct.pack_into("<H", e, 2, i + 1)
        e[4:4 + len(n)] = n.encode()
        struct.pack_into("<hhhh", e, 22, -32768, 32767, -8191, 8191)
        e[30:32] = b"uV"
        struct.pack_into("<I", e, 46, 300); struct.pack_into("<I", e, 50, 4); struct.pack_into("<H", e, 54, 1)
        struct.pack_into("<I", e, 56, 7500); struct.pack_into("<I", e, 60, 3); struct.pack_into("<H", e, 64, 1)
        ext += bytes(e)
    body = b""
    for ts, n in [(0, 10), (150, 8)]:
        body += struct.pack("<BII", 1, ts, n)
        body += rng.randint(-2000, 2000, size=(n, nch)).astype("<i2").tobytes()
    open(os.path.join(D, "test_nsx.ns3"), "wb").write(bytes(hdr) + ext + body)
nsx()

