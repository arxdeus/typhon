# ---- EEGLAB epochs (.set with embedded data) ----
def eeglab_epochs():
    from scipy.io import savemat
    nb, pn, tr = 3, 20, 4
    data = rng.randn(nb, pn, tr)
    chan = np.array([(n,) for n in ["Fz", "Cz", "Pz"]], dtype=[("labels", "O")])
    ev = np.zeros(4, dtype=[("type", "O"), ("latency", "O")])
    ep = np.zeros(4, dtype=[("eventtype", "O"), ("event", "O")])
    for i in range(4):
        ev[i] = ("A" if i % 2 == 0 else "B", float(i * pn + 5))
        ep[i] = ("A" if i % 2 == 0 else "B", i + 1)
    savemat(os.path.join(D, "test_eeglab_ep.set"), {"EEG": {"srate": 100.0, "nbchan": float(nb), "pnts": float(pn), "trials": float(tr),
            "xmin": -0.05, "xmax": 0.14, "data": data, "chanlocs": chan, "event": ev, "epoch": ep, "setname": "x"}})
eeglab_epochs()

