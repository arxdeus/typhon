# ---- Hitachi (3x5 ETG-7000 = 22 pairs -> 44 channels would be large; use 3x3 mode: 12 pairs) ----
def hitachi():
    mode = "3x3"
    from mne.io.hitachi.hitachi import _compute_pairs
    npairs = len(_compute_pairs(3, 3, 2))
    nch = npairs * 2
    lines = ["Header", "File Version,1.0", "AnalyzeMode,Continuous", "Sampling Period[s],0.1", "Comment,test", "Mode,3x3",
             "Date,3/4/20 10:20", "Wave[nm],780,830", "Sex,Male", "Age,30y", "HPF[Hz],0.01", "LPF[Hz],5"]
    names = [f"CH{i + 1}({780 + 50 * (i % 2)}.5)" for i in range(nch)]
    lines.append("Wave Length," + ",".join(names))
    lines.append("Data")
    lines.append("Probe1,Time,Probe2," + ",".join(names) + ",Mark")
    for t in range(12):
        lines.append(f"0,00:00:{t:02d},0," + ",".join(f"{rng.rand():.4f}" for _ in range(nch)) + f",{t % 3}")
    open(os.path.join(D, "test_hitachi.csv"), "w").write("\r\n".join(lines) + "\r\n")
