# Generates test/mne/test_tf_more.py with mne 1.13.2 as the reference.
import os, tempfile, warnings
import numpy as np
import mne
warnings.simplefilter("ignore")
mne.set_log_level("ERROR")
HERE = os.path.dirname(os.path.abspath(__file__))
fexp, sexp = [], []
def check(n, got, rtol=1e-7, atol=1e-15):
    fexp.append((n, [float(x) for x in np.asarray(got, dtype=float).ravel()]))
def checks(n, got):
    sexp.append((n, [str(v) for v in got]))
src = open(os.path.join(HERE, "templates", "test_tf_more.tpl")).read()
pre = open(os.path.join(HERE, "templates", "core_prelude.tpl")).read()
g = {"np": np, "mne": mne, "check": check, "checks": checks, "CPLX": True}
exec(compile(src, "tpl", "exec"), g)
fl = lambda v: "[" + ", ".join(repr(x) for x in v) + "]"
pre = pre.replace("@@FEXP@@", "\n".join(f"    ({n!r}, {fl(v)})," for n, v in fexp)).replace("@@SEXP@@", "\n".join(f"    ({n!r}, {v!r})," for n, v in sexp))
open(os.path.join(HERE, "test_tf_more.py"), "w").write("# Generated by gen_tf_more_expected.py from templates/test_tf_more.tpl (mne 1.13.2)\n" + pre + src.replace("from mne.time_frequency import (EpochsTFRArray,", "from mne.time_frequency import (EpochsTFRComplex as EpochsTFRArray,"))
