# Generates test_simulation.py and test_eog_regression.py (mne 1.13.2 reference values)
import os
import numpy as np
import mne
mne.set_log_level("ERROR")
HERE = os.path.dirname(os.path.abspath(__file__))
exec(open(os.path.join(HERE, "gen_forward_expected.py")).read().split("E = {}")[0])
def lst(a):
    return "[" + ", ".join(repr(float(v)) for v in np.asarray(a, dtype=float).ravel()) + "]"
tpl = open(os.path.join(HERE, "templates", "test_forward_sphere.tpl")).read()
head = tpl[:tpl.index("@test")].replace("# Generated by gen_forward_expected.py from templates/test_forward_sphere.tpl", "# Generated by gen_sim_eog_expected.py")
msph = mne.make_sphere_model(r0=(0.0, 0.0, 0.04), head_radius=0.09)
setup = f'''
info = make_info()
sphere = mne.make_sphere_model(r0=(0.0, 0.0, 0.04), head_radius=0.09)
sphere.mu = np.array({lst(msph["mu"])})
sphere.lambda_ = np.array({lst(msph["lambda"])})
src = mne.setup_volume_source_space(pos={{"rr": sph(5, 0.05, 2), "nn": sph(5, 1.0, 4, z0=0.0)}})
fwd = mne.make_forward_solution(info, None, src, sphere)
'''
info = make_info()
src = mne.setup_volume_source_space(pos=dict(rr=sph(5, 0.05, 2), nn=sph(5, 1.0, 4, z0=0.0)))
fwd = mne.make_forward_solution(info, None, src, msph)
times = np.arange(20) / 100.0
stc = mne.simulation.simulate_sparse_stc(src, 3, times, rng=7)
stc2 = mne.simulation.simulate_sparse_stc(src, 2, times, random_state=3)
cov = mne.make_ad_hoc_cov(info)
ev = mne.simulation.simulate_evoked(fwd, stc, info, cov, nave=10, rng=11)
ev_iir = mne.simulation.simulate_evoked(fwd, stc, info, cov, nave=np.inf)
ev_rs = mne.simulation.simulate_evoked(fwd, stc, info, cov, nave=5, random_state=5, iir_filter=[1, -0.5])
raw = mne.io.RawArray(np.zeros((14, 50)), info.copy())
mne.simulation.add_noise(raw, cov, rng=2)
sim = f'''
@test
def test_sim():
    stc = mne.simulation.simulate_sparse_stc(src, 3, np.arange(20) / 100.0, rng=7)
    close("vert", stc.vertices[0], {lst(stc.vertices[0])})
    close("data", stc.data, {lst(stc.data)})
    stc2 = mne.simulation.simulate_sparse_stc(src, 2, np.arange(20) / 100.0, random_state=3)
    close("vert2", stc2.vertices[0], {lst(stc2.vertices[0])})
    cov = mne.make_ad_hoc_cov(info)
    ev = mne.simulation.simulate_evoked(fwd, stc, info, cov, nave=10, rng=11)
    close("ev", ev.data, {lst(ev.data)})
    ev2 = mne.simulation.simulate_evoked(fwd, stc, info, cov, nave=5, random_state=5, iir_filter=[1.0, -0.5])
    close("ev_rs", ev2.data, {lst(ev_rs.data)})
    raw = mne.io.RawArray(np.zeros((14, 50)), info.copy())
    mne.simulation.add_noise(raw, cov, rng=2)
    close("raw", raw.get_data(), {lst(raw.get_data())})
test_sim()
'''
open(os.path.join(HERE, "test_simulation.py"), "w").write(head + setup + sim)
# EOG regression
rs = np.random.RandomState(0)
names = ["F1", "F2", "P1", "P2", "EOG1"]
inf = mne.create_info(names, 100.0, ["eeg"] * 4 + ["eog"])
eog = rs.randn(200)
data = rs.randn(5, 200) * 1e-6
data[:4] += np.array([0.5, 0.3, 0.1, 0.05])[:, None] * eog[None] * 1e-6 * 3
data[4] = eog * 1e-6 * 3
raw = mne.io.RawArray(data, inf)
raw.set_eeg_reference("average", projection=True)
raw.apply_proj()
m = mne.preprocessing.EOGRegression().fit(raw)
clean = m.apply(raw)
ep = mne.EpochsArray(data.reshape(5, 4, 50).transpose(1, 0, 2), inf, tmin=0.0)
ep.set_eeg_reference("average", projection=True)
ep.apply_proj()
m2 = mne.preprocessing.EOGRegression().fit(ep)
cl2 = m2.apply(ep)
code = f'''
names = ["F1", "F2", "P1", "P2", "EOG1"]
info = mne.create_info(names, 100.0, ["eeg", "eeg", "eeg", "eeg", "eog"])
data = np.array({lst(data)}).reshape(5, 200)


@test
def test_eog():
    raw = mne.io.RawArray(data, info)
    raw.set_eeg_reference("average", projection=True)
    raw.apply_proj()
    m = mne.preprocessing.EOGRegression().fit(raw)
    close("coef", m.coef_, {lst(m.coef_)})
    close("clean", m.apply(raw).get_data(), {lst(clean.get_data())})
    ep = mne.EpochsArray(np.ascontiguousarray(data.reshape(5, 4, 50).transpose(1, 0, 2)), info, tmin=0.0)
    ep.set_eeg_reference("average", projection=True)
    ep.apply_proj()
    m2 = mne.preprocessing.EOGRegression().fit(ep)
    close("coef_ep", m2.coef_, {lst(m2.coef_)})
    close("clean_ep", m2.apply(ep).get_data(), {lst(cl2.get_data())})
test_eog()
'''
open(os.path.join(HERE, "test_eog_regression.py"), "w").write(head + code)
print("ok")
