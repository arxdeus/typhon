# Generates test/mne/test_io_misc.py with mne 1.13.2 as the reference.
import os, sys, tempfile, warnings, datetime
import numpy as np
import mne
warnings.simplefilter("ignore")
mne.set_log_level("ERROR")
HERE = os.path.dirname(os.path.abspath(__file__))
fexp, sexp = [], []
def check(n, got, rtol=1e-7, atol=1e-15):
    fexp.append((n, [float(x) for x in np.asarray(got, dtype=float).ravel()]))
def checks(n, got):
    sexp.append((n, [str(v) for v in got]))
src = open(os.path.join(HERE, "templates", "test_io_misc.tpl")).read()
tmp = tempfile.mkdtemp(); os.mkdir(os.path.join(tmp, "build")); os.chdir(tmp)
V = lambda x: x
g = {"np": np, "mne": mne, "check": check, "checks": checks, "V": V, "datetime": datetime, "GETX": lambda i: [i["experimenter"], i["description"]], "SETX": lambda i: (i.__setitem__("experimenter", "bob"), i.__setitem__("description", "hello")), "DP": lambda k, i, r: dict(kind=k, ident=i, r=np.array(r), coord_frame=4), "List": type("L", (), {"__class_getitem__": classmethod(lambda c, k: list)})}
exec(compile(src, "tpl", "exec"), g)
pre = open(os.path.join(HERE, "templates", "core_prelude.tpl")).read()
fl = lambda v: "[" + ", ".join(repr(x) for x in v) + "]"
pre = pre.replace("@@FEXP@@", "\n".join(f"    ({n!r}, {fl(v)})," for n, v in fexp) or "    ('_', [0.0]),").replace("@@SEXP@@", "\n".join(f"    ({n!r}, {v!r})," for n, v in sexp) or "    ('_', ['']),")
open(os.path.join(HERE, "test_io_misc.py"), "w").write("# Generated by gen_io_misc_expected.py from templates/test_io_misc.tpl (mne 1.13.2)\n" + pre + src.replace("#DPDEF\n", "DP = mne.io.DigPoint\n\ndef GETX(i) -> List[str]:\n    return [str(i.experimenter), str(i.description)]\n\ndef SETX(i):\n    i.experimenter = \"bob\"\n    i.description = \"hello\"\n\n"))
