# Generates test_beamformer.py (mne 1.13.2 reference values; sphere fixture of gen_forward_expected.py)
import os
import numpy as np
import mne
mne.set_log_level("ERROR")
HERE = os.path.dirname(os.path.abspath(__file__))
exec(open(os.path.join(HERE, "gen_forward_expected.py")).read().split("E = {}")[0])
def lst(a):
    return "[" + ", ".join(repr(float(v)) for v in np.asarray(a, dtype=float).ravel()) + "]"
info = mne.pick_info(make_info(), list(range(8, 14)))
sphere = mne.make_sphere_model(r0=(0.0, 0.0, 0.04), head_radius=0.09)
rr = sph(5, 0.05, 2); nn = sph(5, 1.0, 4, z0=0.0)
src = mne.setup_volume_source_space(pos=dict(rr=rr, nn=nn))
fwd = mne.make_forward_solution(info, None, src, sphere)
n = 6
t = np.arange(40)
X = np.array([np.sin(0.3 * (i + 1) * t + i) * (1 + 0.1 * i) for i in range(n)]) * 1e-12
X *= 1e3
C = X @ X.T / 40 + np.eye(n) * 1e-3 * np.diag(X @ X.T / 40).mean()
cov = mne.Covariance(C, info["ch_names"], [], [], 40)
noise = mne.make_ad_hoc_cov(info)
ev = mne.EvokedArray(X, info, tmin=0.0)
E = {}
cases = [("a", dict(reduce_rank=True)), ("b", dict(weight_norm="unit-noise-gain", reduce_rank=True)),
         ("c", dict(weight_norm="nai", reduce_rank=True)),
         ("d", dict(pick_ori="max-power", weight_norm=None, reduce_rank=True)),
         ("e", dict(pick_ori="vector", reduce_rank=True)),
         ("h", dict(depth=0.5, rank="full", reduce_rank=True))]
body = []
for k, kw in cases:
    f = mne.beamformer.make_lcmv(info, fwd, cov, reg=0.05, noise_cov=noise, **kw)
    s = mne.beamformer.apply_lcmv(ev, f)
    kws = ", ".join(f"{a}={b!r}" for a, b in kw.items())
    vec = kw.get("pick_ori") == "vector"
    E[k + "_w"] = lst(f["weights"]); E[k + "_s"] = lst(s.data)
    body.append(f"    f = mne.beamformer.make_lcmv(info, fwd, cov, reg=0.05, noise_cov=noise{', ' if kws else ''}{kws})\n"
                f"    close('{k}_w', f.weights, {E[k+'_w']})\n"
                f"    close('{k}_s', mne.beamformer.apply_lcmv{'_vector' if vec else ''}(ev, f).data, {E[k+'_s']})")
f = mne.beamformer.make_lcmv(info, fwd, cov, reg=0.05, noise_cov=noise, reduce_rank=True)
p = mne.beamformer.apply_lcmv_cov(cov, f)
body.append(f"    f = mne.beamformer.make_lcmv(info, fwd, cov, reg=0.05, noise_cov=noise, reduce_rank=True)\n    close('power', mne.beamformer.apply_lcmv_cov(cov, f).data, {lst(p.data)})")
R = mne.beamformer.make_lcmv_resolution_matrix(f, fwd, info)
body.append(f"    close('resmat', mne.beamformer.make_lcmv_resolution_matrix(f, fwd, info), {lst(R)})")
dip = mne.beamformer.rap_music(ev, fwd, noise, n_dipoles=1)
dipt = mne.beamformer.trap_music(ev, fwd, noise, n_dipoles=1)
rm = "\n".join(f"    close('rap{i}', rd[{i}].amplitude, {lst(d.amplitude)})\n    close('rap{i}p', rd[{i}].pos, {lst(d.pos)})" for i, d in enumerate(dip))
tm = "\n".join(f"    close('trap{i}', td[{i}].amplitude, {lst(d.amplitude)})" for i, d in enumerate(dipt))
src_txt = open(os.path.join(HERE, "templates", "test_forward_sphere.tpl")).read()
head = src_txt[:src_txt.index("@test")]
head = head.replace("# Generated by gen_forward_expected.py from templates/test_forward_sphere.tpl", "# Generated by gen_beamformer_expected.py")
setup = f'''
info = mne.pick_info(make_info(), [8, 9, 10, 11, 12, 13])
sphere = mne.make_sphere_model(r0=(0.0, 0.0, 0.04), head_radius=0.09)
sphere.mu = np.array({lst(mne.make_sphere_model(r0=(0.0,0.0,0.04), head_radius=0.09)["mu"])})
sphere.lambda_ = np.array({lst(mne.make_sphere_model(r0=(0.0,0.0,0.04), head_radius=0.09)["lambda"])})
src = mne.setup_volume_source_space(pos={{"rr": sph(5, 0.05, 2), "nn": sph(5, 1.0, 4, z0=0.0)}})
fwd = mne.make_forward_solution(info, None, src, sphere)
n = 6
X = np.empty((n, 40))
for i in range(n):
    for t in range(40):
        X[i, t] = np.sin(0.3 * (i + 1) * t + i) * (1 + 0.1 * i) * 1e-12
for i in range(n):
    for t in range(40):
        X[i, t] *= 1e3
C = np.dot(X, X.T) / 40
tr = 0.0
for i in range(n):
    tr += C[i, i]
for i in range(n):
    C[i, i] += 1e-3 * tr / n
cov = mne.Covariance(C, info.ch_names, [], [], 40)
noise = mne.make_ad_hoc_cov(info)
ev = mne.EvokedArray(X, info, tmin=0.0)
'''
out = head + setup + "\n\n@test\ndef test_lcmv():\n" + "\n".join(body) + "\ntest_lcmv()\n\n\n@test\ndef test_music():\n    rd = mne.beamformer.rap_music(ev, fwd, noise, n_dipoles=1)\n" + rm + "\n    td = mne.beamformer.trap_music(ev, fwd, noise, n_dipoles=1)\n" + tm + "\ntest_music()\n"
open(os.path.join(HERE, "test_beamformer.py"), "w").write(out)
print("wrote test_beamformer.py")
