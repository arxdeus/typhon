info = mne.pick_info(make_info(), list(range(8)))
src = mne.setup_volume_source_space(pos=dict(rr=sph(5, 0.05, 2), nn=sph(5, 1.0, 4, z0=0.0)))
fwd = mne.make_forward_solution(info, None, src, msph)
n, T = 8, 60
t = np.arange(T)
X = np.array([np.sin(0.2 * (i + 1) * t + i) * (1 + 0.1 * i) + 0.3 * np.cos(0.05 * (i * i + 1) * t) for i in range(n)]) * 1e-6
ev = mne.EvokedArray(X, info, tmin=0.0)
ev.set_eeg_reference("average", projection=True)
ev.apply_proj()
cov = mne.compute_covariance(mne.EpochsArray(X.reshape(1, n, T).repeat(2, 0) + np.random.RandomState(0).randn(2, n, T) * 1e-7, ev.info.copy(), tmin=0.0), verbose=False) if False else None
C = X @ X.T / T
C += np.eye(n) * 1e-2 * np.trace(C) / n
cov = mne.Covariance(C, info["ch_names"], [], ev.info["projs"], T)
noise = mne.make_ad_hoc_cov(info)
body = []
for k, kw in [("a", dict(reduce_rank=False)), ("b", dict(weight_norm="unit-noise-gain", pick_ori="max-power")),
              ("c", dict(weight_norm="nai", reduce_rank=False))]:
    f = mne.beamformer.make_lcmv(ev.info, fwd, cov, reg=0.05, noise_cov=noise, rank="info", **kw)
    s = mne.beamformer.apply_lcmv(ev, f)
    kws = ", ".join(f"{a}={b!r}" for a, b in kw.items())
    body.append(f"    f = mne.beamformer.make_lcmv(ev.info, fwd, cov, reg=0.05, noise_cov=noise, rank='info', {kws})\n"
                f"    close('{k}_w', f.weights, {lst(f['weights'])})\n"
                f"    close('{k}_s', mne.beamformer.apply_lcmv(ev, f).data, {lst(s.data)})")
