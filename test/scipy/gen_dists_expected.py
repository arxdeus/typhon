def fl(v):
    v = float(v)
    if np.isnan(v):
        return "NAN"
    if np.isinf(v):
        return "INF" if v > 0 else "-INF"
    return repr(v)

def lst(a):
    return "[" + ", ".join(fl(v) for v in np.ravel(a)) + "]"

