def fl(v):
    v = float(v)
    if np.isnan(v):
        return "NAN"
    if np.isinf(v):
        return "INF" if v > 0 else "-INF"
    return repr(v)

def lst(a):
    return "[" + ", ".join(fl(v) for v in np.ravel(a)) + "]"

def emit(group):
    out = []
    out.append("# Copyright (C) 2026 the Typhon authors")
    out.append(f"# Expected values generated by test/scipy/gen_dists_expected.py {group} (scipy 1.18.1).")
    out.append("import numpy as np")
    out.append("import scipy.stats as st")
    out.append("from dists_check import check, NAN, INF")
    out.append("")
    out.append("ok = True")
    for name, args, rtol in GROUPS[group]:
        d = getattr(st, name)
        fr = d(*args, loc=LOC, scale=SCALE)
        xs = fr.ppf([0.05, 0.3, 0.5, 0.7, 0.95])
        exp = dict(
            pdf=fr.pdf(xs), logpdf=fr.logpdf(xs), cdf=fr.cdf(xs), sf=fr.sf(xs),
            logcdf=fr.logcdf(xs), logsf=fr.logsf(xs), ppf=fr.ppf(QS), isf=fr.isf(QS))
        mvsk = [float(v) for v in fr.stats(moments='mvsk')]
        ent = float(fr.entropy())
        rvs = fr.rvs(size=5, random_state=np.random.RandomState(1234))
        rvg = fr.rvs(size=5, random_state=np.random.default_rng(42))
        a = "(" + "".join(fl(v) + ", " for v in args) + ")"
        out.append(f"ok &= check('{name}', st.{name}, {a}, {lst(xs)}, {lst(QS)},")
        for k in ['pdf', 'logpdf', 'cdf', 'sf', 'logcdf', 'logsf', 'ppf', 'isf']:
            out.append(f"    {lst(exp[k])},")
        out.append(f"    {lst(mvsk)}, {fl(ent)}, {lst(rvs)}, {lst(rvg)}, {rtol!r})")
    out.append("print('ALL OK' if ok else 'FAILED')")
    out.append("assert ok")
    print("\n".join(out))

emit(sys.argv[1])
