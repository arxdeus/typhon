def closec(a, b, tol: float = 1e-12) -> bool:
    a = np.asarray(a).ravel()
    if a.size != len(b):
        return False
    for i in range(len(b)):
        if abs(a[i] - b[i]) > tol * max(1.0, abs(b[i])):
            print('mismatch at', i, a[i], b[i])
            return False
    return True

