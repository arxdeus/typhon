# Shared helpers for test/scipy/gen_*2_expected.py generators.
import numpy as np, os
HEADER = ['NAN = float("nan")', '', 'def closec(a, b, tol: float = 1e-12) -> bool:', '    a = np.asarray(a).ravel()', '    if a.size != len(b):', "        print('size', a.size, len(b))", '        return False',
 '    for i in range(len(b)):', '        if b[i] != b[i]:', '            if a[i] == a[i]:', "                print('expected nan at', i, a[i])", '                return False', '            continue', '        if abs(a[i] - b[i]) > tol * max(1.0, abs(b[i])):', "            print('mismatch at', i, a[i], b[i])", '            return False', '    return True', '']
def lit(val):
    v = np.asarray(val).ravel()
    if np.iscomplexobj(v):
        return '[' + ', '.join(f'complex({z.real!r}, {z.imag!r})' for z in v) + ']'
    return '[' + ', '.join(('NAN' if z != z else repr(float(z))) for z in v) + ']'
class Gen:
    def __init__(self, ns, tol=None):
        self.ns = ns; self.L = []; self.tol = tol
    def E(self, expr, ref=None, tol=None):
        val = eval(ref or expr, self.ns)
        t = tol or self.tol
        ts = f', {t!r}' if t else ''
        self.L.append(f'    assert closec({expr}, {lit(val)}{ts})')
    def raw(self, s): self.L.append(s)
    def test(self, name):
        if self.L and self.L[-1].startswith('    '):
            pass
        self.L.append(f'@test\ndef {name}():')
    def write(self, path, gen, imports, setup):
        cur = None; out = []
        body = []
        for l in self.L:
            if l.startswith('@test'):
                if cur: body.append(f'{cur}()')
                cur = l.split('def ')[1].split('(')[0]
            body.append(l)
        if cur: body.append(f'{cur}()')
        txt = [f'# Generated by test/scipy/{gen}. Do not edit.'] + imports + [''] + HEADER + setup + [''] + body
        path = os.path.join(os.path.dirname(os.path.abspath(__file__)), os.path.basename(path))
        open(path, 'w').write('\n'.join(txt) + '\n')
