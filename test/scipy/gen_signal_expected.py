def lit(a):
    a = np.asarray(a)
    if np.iscomplexobj(a):
        return "[" + ", ".join(f"complex({repr(float(v.real))}, {repr(float(v.imag))})" for v in a.ravel()) + "]"
    return "[" + ", ".join(repr(float(v)) for v in a.ravel()) + "]"


def X3():
    i = np.arange(40 * 8 * 256, dtype=float).reshape(40, 8, 256)
