def x1(n=200):
    t = np.arange(n, dtype=float)
    return np.sin(0.2 * t) + 0.3 * np.cos(0.05 * t * t / n) + 0.01 * t


def summary(a):
    a = np.asarray(a)
    flat = a.ravel()
    w = np.arange(flat.size) % 13 + 1
    return [flat.sum(), (flat * w).sum(), (flat ** 2).sum()]


