import numpy as np, scipy.stats as st
rng = np.random.default_rng(2)
x = rng.normal(5, 2, 60); cut = 6.5
unc = x[x < cut]; right = np.full((x >= cut).sum(), cut)
cd = st.CensoredData(uncensored=unc, right=right)
pn = st.norm.fit(cd)
ex = rng.exponential(3.0, 50); ce = 4.0
cd2 = st.CensoredData(uncensored=ex[ex < ce], right=np.full((ex >= ce).sum(), ce))
pe = st.expon.fit(cd2, floc=0)
