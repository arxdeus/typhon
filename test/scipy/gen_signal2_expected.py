def lit(a):
    a = np.asarray(a)
    if np.iscomplexobj(a):
        return "[" + ", ".join(f"complex({float(v.real)!r}, {float(v.imag)!r})" for v in a.ravel()) + "]"
    return "[" + ", ".join(repr(float(v)) for v in a.ravel()) + "]"

def dump(fn, d):
    with open(fn, 'w') as f:
        f.write('# Generated by gen_signal2_expected.py (scipy 1.18.1). Do not edit.\n')
        for k, v in d.items():
            f.write(f'{k} = {lit(v)}\n')

