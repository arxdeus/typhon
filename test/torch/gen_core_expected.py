print("# ---- autograd")
w = (torch.arange(12, dtype=torch.float64).reshape(3, 4) / 5 - 1).requires_grad_()
v = (torch.arange(4, dtype=torch.float64) / 3 + 0.2).requires_grad_()
y = (torch.tanh(w @ v).pow(2).sum() + torch.softmax(w, 1)[:, 1].log().mean()
     + (w * v).exp().amax(1).sum() + w.std() + torch.sigmoid(w[1:, ::2]).sum())
y.backward()
print(f"ag_y = {y.item()!r}")
print(f"ag_gw = {L(w.grad)}")
print(f"ag_gv = {L(v.grad)}")
a = torch.linspace(0.1, 2.0, 6, dtype=torch.float64).reshape(2, 3).requires_grad_()
z = (torch.cat([a, a * 2], 0).reshape(3, 4).t()[1:].sqrt().sum()
     + torch.stack([a, a.flip(1)], 2).sum(2).prod() + a.clamp(0.5, 1.5).sum()
     + torch.where(a > 1.0, a ** 3, -a).sum() + a.unsqueeze(0).expand(3, 2, 3).sum())
z.backward()
print(f"ag_z = {z.item()!r}")
print(f"ag_ga = {L(a.grad)}")

print("# ---- linalg / fft")
A = torch.tensor([[4.0, 1.0, 0.5], [1.0, 3.0, 0.2], [0.5, 0.2, 2.0]], dtype=torch.float64, requires_grad=True)
r = torch.linalg.eigh(A)
(r.eigenvalues.sum() + (r.eigenvectors ** 3).sum() + torch.linalg.inv(A).sum() + torch.linalg.cholesky(A).sum()
 + torch.linalg.slogdet(A).logabsdet + torch.linalg.svd(A).S.sum()).backward()
print(f"la_evals = {L(r.eigenvalues)}")
print(f"la_grad = {L(A.grad)}")
x = torch.linspace(0., 1., 8, dtype=torch.float64, requires_grad=True)
X = torch.fft.rfft(x)
y = (X.abs() ** 2).sum() + torch.fft.irfft(X * 2.0, n=8).sum() + torch.fft.fft(x).real.sum()
y.backward()
print(f"fft_X = {L(torch.view_as_real(X))}")
print(f"fft_y = {y.item()!r}")
print(f"fft_grad = {L(x.grad)}")
xf = torch.arange(10, dtype=torch.float32) / 3.0
print(f"rfft_f32 = {L(torch.view_as_real(torch.fft.rfft(xf, norm='forward')))}")

