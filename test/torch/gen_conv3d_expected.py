# Expected values for test/torch/test_conv3d.py (torch 2.15.0).
import torch
def L(t): return repr([float(v) for v in t.detach().reshape(-1).tolist()])
torch.manual_seed(0)
m = torch.nn.Conv3d(2, 4, (3, 2, 3), stride=(1, 2, 1), padding=(1, 0, 2), dilation=(1, 1, 2), groups=2).double()
print(f"w0 = {L(m.weight)}")
print(f"b0 = {L(m.bias)}")
x = (torch.arange(2 * 2 * 4 * 5 * 6, dtype=torch.float64).reshape(2, 2, 4, 5, 6) / 50.0).sin().requires_grad_()
y = m(x)
print(f"yshape = {list(y.shape)}")
(y * y.detach().cos()).sum().backward()
print(f"y = {L(y)}")
print(f"gx = {L(x.grad)}")
print(f"gw = {L(m.weight.grad)}")
print(f"gb = {L(m.bias.grad)}")
torch.manual_seed(1)
m2 = torch.nn.Conv3d(3, 2, 3, padding="same", bias=False)
x2 = torch.randn(1, 3, 4, 4, 5)
print(f"y2 = {L(m2(x2))}")
bn = torch.nn.BatchNorm3d(2).double()
xb = x.detach() * 3 + 1
bn.train(); yb = bn(xb)
print(f"bn_train = {L(yb)}")
print(f"bn_rm = {L(bn.running_mean)}")
print(f"bn_rv = {L(bn.running_var)}")
bn.eval()
print(f"bn_eval = {L(bn(xb))}")
